import {readFile,writeFile} from 'node:fs/promises';

// Keep the browser's local safety checks aligned with the collector. Reports
// cannot weaken these rules by supplying a different policy in an API reply.
const config=JSON.parse(await readFile(new URL('../worker/runner_policy.json',import.meta.url),'utf8'));
const output=`// Generated by scripts/render-runner-policy.mjs. Edit worker/runner_policy.json.\nexport const RUNNER_CONFIG=${JSON.stringify(config,null,2)};\n`;
const target=new URL('../dist/runner-policy.mjs',import.meta.url);
const current=await readFile(target,'utf8').catch(()=>null);
if(current!==output){
 if(process.argv.includes('--check'))throw Error('Runner policy output is stale. Run node scripts/render-runner-policy.mjs.');
 await writeFile(target,output);
}
