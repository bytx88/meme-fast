import {readFile,writeFile} from 'node:fs/promises';

// The Inspect page owns the server-rendered masthead. Keep every page's
// initial HTML in sync without waiting for JavaScript to paint navigation.
const lessons=Array.from({length:8},(_,i)=>`meme-101-level-${i+1}`);
const courseSources=['content/meme-101b/course.json','content/meme-101c/course.json','content/meme-202/202a.json','content/meme-202/202b.json','content/meme-303/303a.json'];
const courses=await Promise.all(courseSources.map(async path=>JSON.parse(await readFile(path,'utf8'))));
const applied=courses.flatMap(course=>[course.slug,...(course.sections||course.lessons).map((_,i)=>`${course.slug}-${course.sections?'section':'lesson'}-${i+1}`)]);
const learning=['learn','meme-101',...lessons,'meme-303',...applied];
const pages=['order-flow','narratives','narrative','new-coins','radar','watchlist','macro','sources','about','model','privacy','terms',...learning];
const pattern=/<header class="masthead">[\s\S]*?<\/header>/;
const canonical=(await readFile('dist/order-flow.html','utf8')).match(pattern)?.[0];
if(!canonical)throw new Error('Inspect masthead missing');
let base=canonical.replace('class="brand" href="./"','class="brand" href="./order-flow.html"');
base=base.replace(/<a href="\.\/(?:meme-101|learn)\.html"[^>]*>(?:Meme 101|Learn)<\/a>/g,'');
base=base.replace(/(<a href="\.\/model\.html"[^>]*>Model<\/a>)/,'<a href="./learn.html">Learn</a>$1');
const active={model:'model.html',narratives:'narratives.html','new-coins':'new-coins.html',radar:'radar.html','order-flow':'order-flow.html',watchlist:'watchlist.html',macro:'macro.html'};
for(const page of learning)active[page]='learn.html';
const check=process.argv.includes('--check');
let stale=false;
for(const page of pages){
 const file=`dist/${page}.html`,source=await readFile(file,'utf8');
 if(!pattern.test(source))throw new Error(`${file} masthead missing`);
 const header=base.replace(/ aria-current="page"/g,'').replace(`<a href="./${active[page]}">`,`<a href="./${active[page]}" aria-current="page">`);
 let generated=source.replace(pattern,header);
 if(['new-coins','radar'].includes(page)){
  const course=page==='new-coins'?'meme-202a':'meme-202b',label=page==='new-coins'?'Snipe':'Swing';
  if(!generated.includes(`href="./${course}.html"`))generated=generated.replace(`<h1>${label}</h1>`,`<h1>${label}</h1><a class="course-help" href="./${course}.html">Learn ${label} →</a>`);
  if(!generated.includes('href="./learning.css'))generated=generated.replace('</head>','<link rel="stylesheet" href="./learning.css?v=1"></head>');
 }
 if(generated!==source){stale=true;if(!check)await writeFile(file,generated)}
}
const snipe=await readFile('dist/new-coins.html','utf8');
const index=await readFile('dist/index.html','utf8');
if(index!==snipe){stale=true;if(!check)await writeFile('dist/index.html',snipe)}
if(check&&stale)throw new Error('Shared page output is stale. Run node scripts/render-shared-pages.mjs.');

// Macro uses the canonical header and its trading density without importing
// styles for the token dashboard. Generate from the same header rules.
const tradingCss=await readFile('dist/trader-ui.css','utf8');
const headerDensity=tradingCss.slice(tradingCss.indexOf('body.trader-ui .masthead {'),tradingCss.indexOf('body.trader-ui .workspace-head,'));
const macroHeader=`/* Generated by render-shared-pages.mjs from shared masthead rules. */
body.macro-shell .masthead{display:flex;justify-content:space-between;max-width:1440px;margin:0 auto 18px;border-bottom:1px solid #91b8ca20;background:transparent;--trader-control-height:32px;font-family:Arial,Helvetica,sans-serif}
body.macro-shell .masthead .brand{display:flex;align-items:center;gap:10px;letter-spacing:.035em;color:#f1f5f9;font-weight:800;text-shadow:0 2px 2px #0006}
body.macro-shell .brand-mark{display:inline-block;flex:none;width:30px;height:30px;border-radius:8px;background:url('./brand-mark.svg?v=2') center/contain no-repeat;box-shadow:0 3px 8px #0008,0 0 22px #2bdfaa18}
body.macro-shell .site-nav{display:flex;align-items:center}
body.macro-shell .site-nav a:hover{text-decoration:none;color:#f0f3f8}
${headerDensity.replaceAll('body.trader-ui','body.macro-shell')}
@media(max-width:1100px){body.macro-shell .masthead{height:auto;min-height:54px;flex-wrap:wrap;gap:5px 10px;padding:6px 0}body.macro-shell .masthead .site-nav{width:100%;order:2;justify-content:flex-start;flex-wrap:wrap}body.macro-shell .masthead .market-overview{margin-left:auto}}
@media(min-width:851px) and (max-width:1100px){body.macro-shell main .masthead{height:54px;min-height:54px;flex-wrap:nowrap;padding:4px 0;gap:12px}body.macro-shell main .masthead .market-overview{flex:0 1 240px;margin-left:0}body.macro-shell main .masthead .site-nav{width:auto;flex-wrap:nowrap;order:initial;white-space:nowrap;gap:2px;margin-left:auto}}
@media(max-width:720px){body.macro-shell .masthead .site-nav a{padding:5px 7px}}
`;
const headerFile='dist/macro-header.css',oldHeader=await readFile(headerFile,'utf8').catch(()=>null);
if(oldHeader!==macroHeader){if(check)throw new Error('Macro header styles are stale');await writeFile(headerFile,macroHeader)}
